// Extend to 4096 bytes (pad the rest with ASCII 127 Box to avoid compilation errors)
// Since this is just a demo font, we define 128 chars above (2048 bytes), and fill the rest.
const FONT_PADDING: [u8; 2048] = [0xFF; 2048];

/// Get character bitmap data from the font
pub fn get_char_data(c: u8) -> &'static [u8] {
    let index = (c as usize) * 16;
    if index < 2048 {
        &VGA_FONT_8X16[index..index + 16]
    } else {
        // Fallback or fill
        &FONT_PADDING[0..16]
    }
}
